"""Build a local ASCII Noto Serif Thin subset for the web and vector PDF.

Requires fonttools and brotli only when regenerating these committed assets.
Pass a Google Fonts commit SHA to reproduce a previous source version.
"""
import base64
import hashlib
import io
import json
import math
import re
import sys
import urllib.parse
import urllib.request
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont


def fetch(url):
    request = urllib.request.Request(url, headers={"User-Agent": "Pentagrama"})
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read()


sha = sys.argv[1] if len(sys.argv) > 1 else json.loads(fetch(
    "https://api.github.com/repos/google/fonts/commits?path=ofl/notoserif&per_page=1"
))[0]["sha"]
if not re.fullmatch(r"[a-f0-9]{40}", sha):
    raise ValueError("Expected a Google Fonts commit SHA")
raw = f"https://raw.githubusercontent.com/google/fonts/{sha}/ofl/notoserif/"
source = fetch(raw + urllib.parse.quote("NotoSerif[wdth,wght].ttf"))
license_text = b"\n".join(line.rstrip() for line in fetch(raw + "OFL.txt").splitlines()) + b"\n"
font = TTFont(io.BytesIO(source), recalcTimestamp=False)
modified = font["head"].modified
instantiateVariableFont(font, {"wght": 100, "wdth": 100}, inplace=True, updateFontNames=True)
options = subset.Options()
options.layout_features = []  # Identical, unkerned advances in SVG and PDF.
options.name_IDs = ["*"]
subsetter = subset.Subsetter(options=options)
subsetter.populate(unicodes=range(32, 127))
subsetter.subset(font)
font["head"].modified = modified

directory = Path(__file__).resolve().parents[1] / "docs" / "vendor"
directory.mkdir(parents=True, exist_ok=True)
ttf = io.BytesIO()
font.save(ttf)
program = ttf.getvalue()
scale = 1000 / font["head"].unitsPerEm
cmap = font.getBestCmap()
metrics = {
    "name": font["name"].getDebugName(6),
    "weight": font["OS/2"].usWeightClass,
    "ascent": math.ceil(font["hhea"].ascent * scale),
    "descent": math.floor(font["hhea"].descent * scale),
    "capHeight": math.ceil(font["OS/2"].sCapHeight * scale),
    "bbox": [math.floor(font["head"].xMin * scale), math.floor(font["head"].yMin * scale),
             math.ceil(font["head"].xMax * scale), math.ceil(font["head"].yMax * scale)],
    "widths": [round(font["hmtx"][cmap[code]][0] * scale, 4) for code in range(32, 127)],
}
(directory / "footer-font-metrics.js").write_text(
    "// Noto Serif Thin ASCII subset; SIL OFL 1.1. See noto-serif-OFL.txt.\n"
    + f"// Source: https://github.com/google/fonts/tree/{sha}/ofl/notoserif\n"
    + "export const FOOTER_FONT = Object.freeze(" + json.dumps(metrics, separators=(",", ":")) + ");\n",
    encoding="utf-8")
(directory / "footer-font-data.js").write_text(
    "// Embedded TrueType program, Noto Serif Thin ASCII subset; SIL OFL 1.1.\n"
    + "// Generated by tools/vendor-footer-font.py. See noto-serif-OFL.txt.\n"
    + "export const FOOTER_FONT_DATA = '" + base64.b64encode(program).decode("ascii") + "';\n",
    encoding="utf-8")
font.flavor = "woff2"
font.save(directory / "noto-serif-thin.woff2")
(directory / "noto-serif-OFL.txt").write_bytes(license_text)
(directory / "noto-serif-SOURCE.md").write_text(
    "# Noto Serif Thin\n\n"
    + f"Source: https://github.com/google/fonts/tree/{sha}/ofl/notoserif\n\n"
    + "SIL Open Font License 1.1; see noto-serif-OFL.txt.\n\n"
    + "Static instance: weight 100, width 100. ASCII U+0020–U+007E; no layout features.\n"
    + "The web font and PDF program use the same outlines and advances.\n\n"
    + f"Original TTF SHA-256: {hashlib.sha256(source).hexdigest()}\n\n"
    + f"Regenerate: `python tools/vendor-footer-font.py {sha}`\n",
    encoding="utf-8")
print(json.dumps({"source": sha, "weight": metrics["weight"], "ttfBytes": len(program),
                  "woff2Bytes": (directory / "noto-serif-thin.woff2").stat().st_size}))

"""Generate the three shared Bravura clef outlines (no runtime font dependency)."""
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'tools' / '.glyph-deps'))
from fontTools.ttLib import TTFont
from fontTools.pens.basePen import BasePen
from fontTools.pens.boundsPen import BoundsPen

source = json.loads((ROOT / 'tools/vendor/bravura-source.json').read_text())
font_path = ROOT / 'tools/vendor/Bravura.otf'
assert hashlib.sha256(font_path.read_bytes()).hexdigest() == source['fontSha256']
font = TTFont(font_path)
glyph_set = font.getGlyphSet()
cmap = font.getBestCmap()
space = font['head'].unitsPerEm / 4
metadata = json.loads((ROOT / 'tools/vendor/bravura_metadata.json').read_text())

class Outline(BasePen):
    def __init__(self):
        super().__init__(glyph_set)
        self.commands = []
    def xy(self, point):
        return [round(point[0] / space, 6), round(-point[1] / space, 6)]
    def _moveTo(self, point): self.commands.append(['M', *self.xy(point)])
    def _lineTo(self, point): self.commands.append(['L', *self.xy(point)])
    def _curveToOne(self, a, b, c): self.commands.append(['C', *self.xy(a), *self.xy(b), *self.xy(c)])
    def _closePath(self): self.commands.append(['Z'])
    def _endPath(self): raise ValueError('Unexpected open glyph contour')

glyphs = {}
for name, codepoint in [('gClef', 0xE050), ('fClef', 0xE062), ('cClef', 0xE05C)]:
    glyph = glyph_set[cmap[codepoint]]
    pen, bounds = Outline(), BoundsPen(glyph_set)
    glyph.draw(pen); glyph.draw(bounds)
    left, bottom, right, top = bounds.bounds
    expected = metadata['glyphBBoxes'][name]
    actual = [left / space, bottom / space, right / space, top / space]
    for a, b in zip(actual, [*expected['bBoxSW'], *expected['bBoxNE']]):
        assert abs(a - b) < 0.005, (name, actual, expected)
    glyphs[name] = {'bounds': dict(zip(['left','top','right','bottom'], [round(left/space,6),round(-top/space,6),round(right/space,6),round(-bottom/space,6)])), 'commands': pen.commands}

output = '// Generated by tools/extract-clefs.py from Bravura; SIL OFL 1.1.\n'
output += '// Coordinates: staff spaces; positive y points down. See tools/vendor/bravura-source.json.\n'
output += 'export const CLEF_GLYPHS = ' + json.dumps(glyphs, ensure_ascii=False, separators=(',',':')) + ';\n'
(ROOT / 'docs/vendor/clef-glyphs.js').write_text(output, encoding='utf-8')
print('Generated Bravura clef outlines:', ', '.join(glyphs))

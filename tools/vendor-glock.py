"""Prepare the small CC0 VSCO glock bank. Development only: Python + NumPy."""
import argparse
import hashlib
import io
import json
from pathlib import Path
import urllib.request
import wave

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
REVISION = '440300901dfe9275fd84e0b7763af1f8443ae62e'
BASE = f'https://raw.githubusercontent.com/sgossner/VSCO-2-CE/{REVISION}/'
SOURCES = [
    ('G5', 'g6', 'dbaf80bc3975016095de3a611a202b581931311c'),
    ('C6', 'c7', 'c02ff721d10eb3551372806653368f45ea5dc367'),
    ('G6', 'g7', 'e95738492bdc207b11ad32891a9a1ea090b6719e'),
]
parser = argparse.ArgumentParser()
parser.add_argument('--source-dir', type=Path, help='Reuse previously downloaded source WAVs and LICENSE')
args = parser.parse_args()
destination = ROOT / 'docs/vendor/glock'
destination.mkdir(parents=True, exist_ok=True)


def source(name, path):
    if args.source_dir:
        return (args.source_dir / name).read_bytes()
    with urllib.request.urlopen(BASE + path, timeout=30) as response:
        return response.read()


manifest = []
for original, name, expected in SOURCES:
    filename = f'glock_medium_{original}.wav'
    path = f'Percussion/Glock/{filename}'
    raw = source(filename, path)
    blob = hashlib.sha1(f'blob {len(raw)}\0'.encode() + raw).hexdigest()
    if blob != expected:
        raise ValueError(f'Unexpected source hash: {filename}')
    with wave.open(io.BytesIO(raw), 'rb') as audio:
        if audio.getsampwidth() != 2 or audio.getframerate() != 44100:
            raise ValueError('Expected 16-bit 44.1 kHz PCM')
        rate = audio.getframerate()
        samples = np.frombuffer(audio.readframes(audio.getnframes()), '<i2').reshape(-1, audio.getnchannels()).mean(axis=1) / 32768
    # Source octave labels differ from concert pitch. Measure the fundamental,
    # including the original instrument's small tuning offset, before trimming.
    attack = np.flatnonzero(abs(samples) > abs(samples).max() * .02)[0]
    section = samples[attack + int(.08 * rate):attack + int(.58 * rate)]
    spectrum = abs(np.fft.rfft(section * np.hanning(len(section)), n=262144))
    frequencies = np.fft.rfftfreq(262144, 1 / rate)
    candidates = np.flatnonzero((frequencies > 600) & (frequencies < 4500))
    index = candidates[np.argmax(spectrum[candidates])]
    logarithms = np.log(spectrum[index - 1:index + 2])
    offset = .5 * (logarithms[0] - logarithms[2]) / (logarithms[0] - 2 * logarithms[1] + logarithms[2])
    frequency = (index + offset) * rate / 262144
    root_midi = 69 + 12 * np.log2(frequency / 440)
    start = max(0, np.flatnonzero(abs(samples) > abs(samples).max() * .004)[0] - int(.002 * rate))
    samples = samples[start:start + rate * 4].copy()
    samples -= samples.mean()
    samples *= .82 / abs(samples).max()
    samples[:32] *= np.linspace(0, 1, 32)
    fade = int(.25 * rate)
    samples[-fade:] *= np.linspace(1, 0, fade) ** 2
    pcm = np.rint(samples * 32767).astype('<i2').tobytes()
    output = destination / f'{name}.wav'
    with wave.open(str(output), 'wb') as audio:
        audio.setnchannels(1)
        audio.setsampwidth(2)
        audio.setframerate(rate)
        audio.writeframes(pcm)
    manifest.append({
        'file': f'{name}.wav', 'rootMidi': round(float(root_midi), 6),
        'source': path, 'sourceBlob': blob,
        'sha256': hashlib.sha256(output.read_bytes()).hexdigest(),
        'sampleRate': rate, 'frames': len(samples),
    })

(destination / 'manifest.json').write_text(json.dumps({'revision': REVISION, 'transpose': 24, 'samples': manifest}, indent=2) + '\n', encoding='utf-8')
(destination / 'bank.js').write_text('// Generated by tools/vendor-glock.py; recordings are CC0.\nexport const TRANSPOSE = 24;\nexport const GLOCK_SAMPLES = Object.freeze([\n' + ''.join(
    f'  Object.freeze({{ url: new URL("./{item["file"]}?v={item["sha256"][:12]}", import.meta.url).href, rootMidi: {item["rootMidi"]} }}),\n'
    for item in manifest) + ']);\n', encoding='utf-8')
(destination / 'LICENSE.txt').write_bytes(source('LICENSE', 'LICENSE'))
print(f'Prepared {len(manifest)} real glockenspiel samples ({sum((destination / item["file"]).stat().st_size for item in manifest):,} bytes)')

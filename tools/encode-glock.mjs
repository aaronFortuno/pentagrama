// Maintenance only. Accept the upstream lamejs 1.2.1 bundle; never ship the encoder.
import { readFile, writeFile, unlink } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import vm from 'node:vm';

const root = new URL('../docs/vendor/glock/', import.meta.url);
const script = await readFile(process.argv[2]);
if (createHash('sha256').update(script).digest('hex') !== '026bd88846040f357a937cd85821a48492a362eff0812cda734f23fca55fea3b') throw new Error('Expected official lamejs 1.2.1 lame.all.js');
const scope = { Int16Array, Float32Array, Int32Array, Float64Array, Uint8Array, console };
vm.runInNewContext(script.toString(), scope);
const manifest = JSON.parse(await readFile(new URL('manifest.json', root)));
for (const sample of manifest.samples) {
  if (!/^(g6|c7|g7)\.wav$/.test(sample.file)) throw new Error('Regenerate the PCM bank first');
  const pcm = await readFile(new URL(sample.file, root));
  if (createHash('sha256').update(pcm).digest('hex') !== sample.sha256 || pcm.readUInt16LE(20) !== 1 || pcm.readUInt16LE(22) !== 1 || pcm.readUInt32LE(24) !== 44100 || pcm.toString('ascii', 36, 40) !== 'data') throw new Error('Unexpected PCM source');
  const values = new Int16Array(pcm.buffer.slice(pcm.byteOffset + 44, pcm.byteOffset + pcm.length));
  const encoder = new scope.lamejs.Mp3Encoder(1, 44100, 160), chunks = [];
  for (let offset = 0; offset < values.length; offset += 1152) {
    const chunk = encoder.encodeBuffer(values.subarray(offset, offset + 1152));
    if (chunk.length) chunks.push(Buffer.from(chunk));
  }
  chunks.push(Buffer.from(encoder.flush()));
  const mp3 = Buffer.concat(chunks), original = sample.file;
  sample.file = original.replace('.wav', '.mp3'); sample.pcmSha256 = sample.sha256;
  sample.sha256 = createHash('sha256').update(mp3).digest('hex');
  await writeFile(new URL(sample.file, root), mp3);
  await unlink(new URL(original, root));
}
manifest.encoding = 'MP3 mono 160 kbps / 44.1 kHz, lamejs 1.2.1';
await writeFile(new URL('manifest.json', root), JSON.stringify(manifest, null, 2) + '\n');
await writeFile(new URL('bank.js', root), '// Generated by tools/vendor-glock.py and tools/encode-glock.mjs; recordings are CC0.\nexport const TRANSPOSE = 24;\nexport const GLOCK_SAMPLES = Object.freeze([\n' + manifest.samples.map(sample => `  Object.freeze({ url: new URL("./${sample.file}?v=${sample.sha256.slice(0, 12)}", import.meta.url).href, rootMidi: ${sample.rootMidi} }),\n`).join('') + ']);\n');
console.log(`Prepared ${manifest.samples.length} compact MP3 samples`);
